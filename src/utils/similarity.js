// Cosine similarity: measures the angle between two vectors, ignoring
// magnitude. Returns a value from -1 (opposite meaning) to 1 (identical
// meaning). This is the standard metric for comparing text embeddings.
export function cosineSimilarity(vecA, vecB) {
  let dot = 0;
  let normA = 0;
  let normB = 0;

  for (let i = 0; i < vecA.length; i++) {
    dot += vecA[i] * vecB[i];
    normA += vecA[i] * vecA[i];
    normB += vecB[i] * vecB[i];
  }

  if (normA === 0 || normB === 0) return 0;

  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}
